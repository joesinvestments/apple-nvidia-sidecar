#!/usr/bin/env python3
"""The exchange window's table build rejects an expert id outside the layer's table.

exl3-metal/exl3_metal.metal (xw_wait_build, the D0 dispatch of the exchange window) reads the expert id
e of every cold pair from the 4080's slot (const int e = pi[3u * p]) and range-checks only the row r.
e is stored into uexp and then used as the table index:

    const ulong a = table[(ulong)w.layer * w.n_experts + (ulong)uexp[u]];

A negative or too-large e therefore indexes outside the layer's n_experts entries: on the real GPU that is
a read of another layer's entry or of memory past the table, and the !a null check below cannot catch it
because the slot it lands on is not the one that belongs to that expert.  The window goes on and encodes
D1..D6 over whatever blob it found.

This test compiles the tree's own xw_wait_build (the structs and the kernel, cut out of the .metal by its
declarations) as C++ against a small shim for the Metal qualifiers, and runs it on a fake exchange region:
a zeroed region of XCH_REGION_BYTES, a layer slot with planted pairs, and a table whose layer block holds
one tagged blob per expert, with a tagged poison blob in every slot outside the block.  The poison slot is
a valid pointer, so the code that reads out of bounds does not crash: it fills the unit with the poison
blob and returns with the window alive, and that is the wrong result the test records.  The status words,
dead flag, indirect arguments and unit blobs are what each case checks.

Cases (one PASS or FAIL line each):
  ordinary window           valid experts: same units, pairs, CSR and arguments before and after the fix
  one past the last expert  e = n_experts: the dark slot right after the block must be a shape failure
  two past the last expert  e = n_experts + 2: the same, further out
  negative expert id        e = -1: the slot before the block (the 64-bit index wraps to -1) must fail
  valid pair then a bad one a window killed by the second pair's expert leaves no argument behind
  empty layer table         n_experts = 0: every expert id is out of range

Run: python3 tests/test_fix_0010_0.py
No network, no GPU, no model: the kernel is compiled with the host's c++ and run on the CPU.
"""
import os
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent


def find_root():
    """The tree under test: the copy prove_test runs us in, else the one this file sits in."""
    rel = Path("exl3-metal") / "exl3_metal.metal"
    for base in (Path.cwd(), HERE.parent):
        if (base / rel).is_file():
            return base
    return Path.cwd()


ROOT = find_root()
SRC = ROOT / "exl3-metal" / "exl3_metal.metal"
HDR = ROOT / "include" / "strata" / "xch" / "xch_layout.h"

